// Generates schema/ts/*.ts from the committed JSON Schemas (which are themselves
// generated from Go structs by `metarush schema export`).
import { compile } from 'json-schema-to-typescript';
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.join(dir, 'ts');
await mkdir(outDir, { recursive: true });
const banner = '/* eslint-disable */\n// GENERATED by schema/gen-types.mjs from Go structs — do not edit.\n';
const files = (await readdir(dir)).filter((f) => f.endsWith('.schema.json')).sort();
const index = [];
for (const f of files) {
  const raw = JSON.parse(await readFile(path.join(dir, f), 'utf8'));
  const base = f.replace('.schema.json', '');
  const rootName = raw.$ref ? raw.$ref.split('/').pop() : base;
  const schema = normalize(raw, rootName);
  const ts = await compile(schema, rootName, { bannerComment: banner, additionalProperties: false, unreachableDefinitions: true, strictIndexSignatures: false, format: false, ignoreMinAndMaxItems: true });
  const outName = base.replace(/\./g, '-') + '.ts';
  await writeFile(path.join(outDir, outName), ts);
  index.push(`export * as ${camel(base)} from './${outName.replace('.ts', '')}';`);
}
// Convenience flat re-exports for the two most used documents.
index.push("export type { RenderPlan, PlanClip, PlanAudio, PlanOverlay, PlanCaptions, PlanCaptionLine, PlanWord, PlanFraming, PlanTransition, Brand, SafeArea, FrameRange, GainPoint, PlanVoiceover, PlanBeat, PlanMix, PlanClipAudio, PlanVariant, PlanResource, PlanResourcePage, NestedPlan, PlanConversation, PlanShot, PlanTile, PlanRect, PlanTag, PlanCard, PlanSegment, PlanBorder } from './render-plan';");
index.push("export type { Spec, Clip, Overlay, AudioTrack, Captions, Output, Voiceover, Beat, Anchor, TakeRef, Mix, Bus, ResourcePin, ConversationPin, ConversationMember, Shot, OverlaySpan, OverlayChange, LayoutStyle, PiPStyle, SideBySideStyle } from './edit-spec';");
index.push("export type { Ops as OpMap } from './ops';");
index.push("export type { LowerThirdParams } from './template-lower-third-clean';");
index.push("export type { QuoteParams } from './template-quote-kinetic';");
index.push("export type { EndCardParams } from './template-endcard-cta';");
index.push("export type { DataCardParams } from './template-datacard-stat';");
index.push("export type { TitleCardParams } from './template-title-card';");
index.push("export type { LogoCornerParams } from './template-logo-corner';");
index.push("export type { NameBarParams } from './template-name-bar';");
index.push("export type { EndScreenParams } from './template-end-screen';");
await writeFile(path.join(outDir, 'index.ts'), banner + index.join('\n') + '\n');
console.log(`generated ${files.length} type files in ${outDir}`);

// json-schema-to-typescript resolves `definitions` reliably; translate 2020-12
// `$defs`, drop the URN $id and inline the root $ref.
function normalize(raw, rootName) {
  const text = JSON.stringify(raw).replaceAll('#/$defs/', '#/definitions/');
  const s = JSON.parse(text);
  delete s.$id;
  delete s.$schema;
  delete s.title;
  s.definitions = s.$defs || {};
  delete s.$defs;
  if (s.$ref) {
    const root = s.definitions[rootName];
    delete s.$ref;
    Object.assign(s, root);
    delete s.definitions[rootName];
    // References back to the root type (a render plan's nested plans) point
    // at the document root, which is that type now.
    const self = `#/definitions/${rootName}`;
    const walk = (n) => {
      if (Array.isArray(n)) return n.forEach(walk);
      if (n && typeof n === 'object') {
        if (n.$ref === self) n.$ref = '#';
        Object.values(n).forEach(walk);
      }
    };
    walk(s);
  }
  return s;
}

function camel(s) {
  return s.replace(/[-.](\w)/g, (_, c) => c.toUpperCase());
}
