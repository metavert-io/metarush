// A generation record is written once (D125): how it is made when it is
// asked for, then each later part (the ticket, the outcome, the settlement, the
// clean-up at the provider) when it becomes known, and nothing is ever
// overwritten or deleted. setOnce writes a part only while it is still empty.
func setOnce(ctx context.Context, a *app.App, genID, field string, v any) error {
	_, err := a.DB.C(store.CGenerations).UpdateOne(ctx, bson.M{"_id": genID, "workspaceId": a.WorkspaceID(), field: bson.M{"$exists": false}},
		bson.M{"$set": bson.M{field: v}})
	return err
}

// appendTo adds an entry to a list in a record (the sends), never changing what is there.
func appendTo(ctx context.Context, a *app.App, genID, field string, v any) error {
	_, err := a.DB.C(store.CGenerations).UpdateOne(ctx, bson.M{"_id": genID, "workspaceId": a.WorkspaceID()}, bson.M{"$push": bson.M{field: v}})
	return err
}

func loadGen(ctx context.Context, a *app.App, id string) (*models.Generation, error) {
	var g models.Generation
	if err := a.DB.GetByID(ctx, store.CGenerations, a.WorkspaceID(), id, &g); err != nil {
		return nil, apperr.New(apperr.NotFound, "That generated video isn't in this workspace.").WithDetails(map[string]any{"id": id})
	}
	return &g, nil
}

// videoOnly refuses a record of another kind of AI work (D226): those are
// shown and stopped with metarush ai.
func videoOnly(g *models.Generation) (*models.Generation, error) {
	if g.KindOf() != models.GenKindVideo {
		return nil, apperr.New(apperr.NotFound, "That isn't a generated video: it is other AI work.").
			WithDetails(map[string]any{"id": g.ID, "kind": g.Kind}).WithCommand("metarush ai show " + g.ID)
	}
	return g, nil
}

// resolveGen finds a generation by its ID, or by a clip it made.
func resolveGen(ctx context.Context, a *app.App, id string) (*models.Generation, error) {
	id = strings.TrimSpace(id)
	switch {
	case ids.Valid(ids.Generation, id):
		g, err := loadGen(ctx, a, id)
		if err != nil {
			return nil, err
		}
		return videoOnly(g)
	case ids.Valid(ids.Asset, id):
		var g models.Generation
		err := a.DB.C(store.CGenerations).FindOne(ctx, bson.M{"workspaceId": a.WorkspaceID(), "outcome.outputs.assetId": id, "kind": bson.M{"$in": models.VideoKinds}}).Decode(&g)
		if err != nil {
			return nil, apperr.New(apperr.NotFound, "That clip wasn't generated by MetaRush.").WithDetails(map[string]any{"assetId": id})
		}
		return &g, nil
	}
	return nil, apperr.New(apperr.InvalidInput, "Say which generated video: its generation or its clip.").WithDetails(map[string]any{"id": id})
}

// stateOf is a generation's state as people read it.
func stateOf(g *models.Generation, j *models.Job) string {
	switch {
	case g.Outcome != nil:
		return g.Outcome.State
	case j != nil && j.State == models.JobCanceled:
		return StateCanceled
	case j != nil && j.State == models.JobFailed:
		return StateFailed
	case g.Ticket != nil:
		return StateMaking
	case len(g.Sending) > len(g.Sends):
		return StateSending
	}
	return StateWaiting
}

// what names a generation in a few words: "a 6-second shot", "an 8-second
// shot" (the article follows how the number is said), "6 more seconds of a
// clip".
func what(g *models.Generation) string {
	s := g.Params.Seconds
	switch g.Operation {
	case models.GenExtend:
		return fmt.Sprintf("%d more seconds of a clip", s)
	case models.GenEdit:
		return "a changed clip"
	case models.GenLookTest:
		return "a test shot of a look"
	}
	return fmt.Sprintf("%s %d-second shot", plainwords.AOrAn(s), s)
}

func providerTitle(g *models.Generation) string {
	if g.ProviderTitle != "" {
		return g.ProviderTitle
	}
	return g.Provider
}

func summaryOf(g *models.Generation, state string, clips []GenClip) string {
	who := providerTitle(g)
	thing := upperFirst(what(g))
	switch state {
	case StateWaiting:
		return thing + ": waiting to be sent to " + who + "."
	case StateSending:
		return thing + ": being sent to " + who + "."
	case StateMaking:
		return thing + ": " + who + " is making it."
	case StateDone:
		s := thing + " is ready"
		if len(clips) > 0 {
			s = fmt.Sprintf("Ready: “%s” (%s)", clips[0].Title, secondsWords(clips[0].Duration))
		}
		if g.Outcome != nil && g.Outcome.Partial {
			s += ". It came back shorter than asked"
		}
		return s + "."
	case StateRefused:
		return who + " declined " + what(g) + ": its safety filters blocked it."
	case StateCanceled:
		return thing + " was stopped."
	}
	if g.Outcome != nil && g.Outcome.Message != "" {
		return g.Outcome.Message
	}
	return thing + " couldn't be made."
}

func secondsWords(d float64) string {
	if d < 9.95 {
		return fmt.Sprintf("%.1f seconds", d)
	}
	return fmt.Sprintf("%.0f seconds", d)
}

func upperFirst(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

func costOf(g *models.Generation) float64 {
	switch {
	case g.Settled != nil:
		return g.Settled.USD
	case g.Outcome != nil && g.Outcome.Actual != nil:
		return g.Outcome.Actual.USD
	}
	return g.Estimate.USD
}

// views builds views of generations, with their clips and jobs (one query each).
func views(ctx context.Context, a *app.App, gs []models.Generation) []GenView {
	jobIDs, assetIDs := bson.A{}, bson.A{}
	for _, g := range gs {
		if g.JobID != "" {
			jobIDs = append(jobIDs, g.JobID)
		}
		if g.Outcome != nil {
			for _, o := range g.Outcome.Outputs {
				assetIDs = append(assetIDs, o.AssetID)
			}
		}
	}
	jobsBy := map[string]*models.Job{}
	if len(jobIDs) > 0 {
		var js []models.Job
		_ = a.DB.Find(ctx, store.CJobs, a.WorkspaceID(), bson.M{"_id": bson.M{"$in": jobIDs}}, &js)
		for i := range js {
			jobsBy[js[i].ID] = &js[i]
		}
	}
	assetsBy := map[string]*models.Asset{}
	if len(assetIDs) > 0 {
		var as []models.Asset
		_ = a.DB.Find(ctx, store.CAssets, a.WorkspaceID(), bson.M{"_id": bson.M{"$in": assetIDs}}, &as, options.Find().SetProjection(bson.M{"name": 1, "title": 1, "media": 1, "projectIds": 1, "variants": 1, "state": 1}))
		for i := range as {
			assetsBy[as[i].ID] = &as[i]
		}
	}
	revoked := revokedConsents(ctx, a, gs)
	out := make([]GenView, 0, len(gs))
	for _, g := range gs {
		j := jobsBy[g.JobID]
		v := GenView{Generation: g, Clips: []GenClip{}, CostUSD: costOf(&g)}
		v.State = stateOf(&g, j)
		if j != nil {
			v.Job = &GenJobBrief{ID: j.ID, State: j.State, Progress: j.Progress}
		}
		if g.Outcome != nil {
			for _, o := range g.Outcome.Outputs {
				c := GenClip{AssetID: o.AssetID, Duration: o.Duration, ProjectID: g.ProjectID, Title: "Generated clip"}
				if as := assetsBy[o.AssetID]; as != nil {
					c.Title, c.HasThumb = as.DisplayTitle(), as.Variants != nil && as.Variants[models.VariantThumbnail].StorageKey != ""
					if len(as.ProjectIDs) > 0 {
						c.ProjectID = as.ProjectIDs[0]
					}
				}
				c.Link = links.Asset(c.ProjectID, o.AssetID)
				v.Clips = append(v.Clips, c)
			}
		}
		for _, id := range g.ConsentIDs {
			if revoked[id] {
				v.ConsentRevoked = true
			}
		}
		v.Summary = summaryOf(&g, v.State, v.Clips)
		out = append(out, v)
	}
	return out
}

func revokedConsents(ctx context.Context, a *app.App, gs []models.Generation) map[string]bool {
	idsIn := bson.A{}
	for _, g := range gs {
		for _, id := range g.ConsentIDs {
			idsIn = append(idsIn, id)
		}
	}
	out := map[string]bool{}
	if len(idsIn) == 0 {
		return out
	}
	var cs []models.Consent
	_ = a.DB.Find(ctx, store.CConsents, a.WorkspaceID(), bson.M{"_id": bson.M{"$in": idsIn}, "revokedAt": bson.M{"$exists": true}}, &cs)
	for _, c := range cs {
		out[c.ID] = true
	}
	return out
}

func listGens(ctx context.Context, a *app.App, in *GenListIn) (*GenListOut, error) {
	filter := bson.M{"kind": bson.M{"$in": models.VideoKinds}}
	if in.ProjectID != "" {
		filter["projectId"] = in.ProjectID
	}
	if in.Look != "" {
		l, err := findLook(ctx, a, in.Look)
		if err != nil {
			return nil, err
		}
		filter["look.id"] = l.ID
	}
	if in.AssetID != "" {
		g, err := resolveGen(ctx, a, in.AssetID)
		if err != nil {
			return nil, err
		}
		filter["groupId"] = g.GroupID
	}
	limit := int64(in.Limit)
	if limit <= 0 {
		limit = 100
	}
	var gs []models.Generation
	if err := a.DB.Find(ctx, store.CGenerations, a.WorkspaceID(), filter, &gs, options.Find().SetSort(bson.D{{Key: "createdAt", Value: -1}}).SetLimit(limit)); err != nil {
		return nil, err
	}
	out := &GenListOut{Generations: views(ctx, a, gs)}
	done := 0
	for _, v := range out.Generations {
		if v.Settled != nil {
			out.SpentUSD += v.Settled.USD
		}
		if v.State == StateDone {
			done++
		}
	}
	out.SpentUSD = roundMoney(out.SpentUSD)
	switch len(gs) {
	case 0:
		out.Summary = "No generated videos yet."
	default:
		out.Summary = fmt.Sprintf("%s, %d ready, %s spent.", plural(len(gs), "generated video"), done, money(out.SpentUSD))
	}
	return out, nil
}

func showGen(ctx context.Context, a *app.App, id string) (*GenView, error) {
	g, err := resolveGen(ctx, a, id)
	if err != nil {
		return nil, err
	}
	v := views(ctx, a, []models.Generation{*g})[0]
	// Where its clips are used (the cuts that play them).
	for _, c := range v.Clips {
		if res, err := ops.CallTyped[ops.AssetWhereOut](ctx, a, "asset.where", ops.AssetRefIn{AssetID: c.AssetID}, ops.CallerFrom(ctx)); err == nil {
			for _, u := range res.Uses {
				if u.Kind == "cut" || u.Kind == "nested" {
					v.UsedIn = append(v.UsedIn, u)
				}
			}
		}
	}
	if g.ParentID != "" {
		if p, err := loadGen(ctx, a, g.ParentID); err == nil {
			pv := views(ctx, a, []models.Generation{*p})[0]
			v.Parent = &GenBrief{ID: p.ID, Operation: p.Operation, Take: p.Take, State: pv.State, Prompt: clip(p.Prompt, 120)}
		}
	}
	var kids []models.Generation
	_ = a.DB.Find(ctx, store.CGenerations, a.WorkspaceID(), bson.M{"$or": bson.A{bson.M{"parentId": g.ID}, bson.M{"groupId": g.GroupID, "_id": bson.M{"$ne": g.ID}}}, "kind": bson.M{"$in": models.VideoKinds}}, &kids,
		options.Find().SetSort(bson.D{{Key: "createdAt", Value: 1}}).SetLimit(50))
	for _, kv := range views(ctx, a, kids) {
		v.Children = append(v.Children, GenBrief{ID: kv.ID, Operation: kv.Operation, Take: kv.Take, State: kv.State, Prompt: clip(kv.Prompt, 120)})
	}
	return &v, nil
}

func roundMoney(v float64) float64 { return float64(int64(v*1000+0.5)) / 1000 }

func firstNonEmpty(vs ...string) string {
	for _, v := range vs {
		if s := strings.TrimSpace(v); s != "" {
			return s
		}
	}
	return ""
}

func plural(n int, one string) string {
	if n == 1 {
		return "1 " + one
	}
	return fmt.Sprintf("%d %ss", n, one)
}

func clip(s string, n int) string {
	s = strings.Join(strings.Fields(s), " ")
	if r := []rune(s); len(r) > n {
		return string(r[:n-1]) + "…"
	}
	return s
}

// channelOf says through which surface a request came.
func channelOf(actor models.Actor, origin string) string {
	switch {
	case strings.HasPrefix(origin, "assistant:"):
		return "claude-panel"
	case actor.Via == "":
		return "cli"
	}
	return actor.Via
}
