"""Writes the Homebrew tap files for a published MetaRush release: the formula, the cask and the README.

    python3 -I scripts/brew-formula.py <owner/repo> <vX.Y.Z> <release.json> <checksums.txt> <out dir> <owner/homebrew-tap>

writes <out dir>/Formula/metarush.rb, <out dir>/Casks/metarush.rb and <out dir>/README.md.

Both download the release archives through the GitHub API (/releases/assets/<id>, Accept:
application/octet-stream), with the token in HOMEBREW_GITHUB_API_TOKEN when one is set (it only
raises GitHub's rate limit). Homebrew drops the Authorization header when the API redirects to
the signed download URL (D77).

- The cask is the recommended install: it only unpacks the pre-built binary, so Homebrew does
  not run its build-from-source checks (a formula without bottles needs current Command Line
  Tools on macOS). Cask downloads are quarantined; the binary is not signed or notarized yet, so
  the cask clears the quarantine flag of what it unpacked.
- The formula also installs ffmpeg and Node.js (its dependencies) and the renderer package,
  skills and docs under share/.
"""

import json
import os
import sys

repo, tag, release_json, checksums_txt, out_dir, tap = sys.argv[1:7]
version = tag[1:] if tag.startswith("v") else tag
owner = repo.split("/")[0]
tap_name = tap.split("/", 1)[1].removeprefix("homebrew-")

with open(release_json) as f:
    assets = {a["name"]: a["id"] for a in json.load(f)["assets"]}
sums = {}
with open(checksums_txt) as f:
    for line in f:
        parts = line.split()
        if len(parts) == 2:
            sums[parts[1]] = parts[0]


def archive(os_name, arch):
    name = f"metarush_{version}_{os_name}_{arch}.tar.gz"
    if name not in assets or name not in sums:
        sys.exit(f"the release has no {name}")
    return f"https://api.github.com/repos/{repo}/releases/assets/{assets[name]}", sums[name]


def formula_block(os_name, arch):
    url, sha = archive(os_name, arch)
    return f'      url "{url}",\n          headers: METARUSH_HEADERS\n      sha256 "{sha}"\n'


def cask_block(os_name, arch):
    url, sha = archive(os_name, arch)
    return f'      sha256 "{sha}"\n      url "{url}",\n          header: headers\n'


header_comment = f"""# Generated by scripts/release.sh in {repo} for {tag}. Do not edit: the next release rewrites it.
#
# Homebrew downloads the release archives through the GitHub API; HOMEBREW_GITHUB_API_TOKEN, when set,
# only raises GitHub's rate limit. See docs/installation.md in the archive."""

NEXT_STEPS = """Next step:
  metarush setup                   # a few questions with suggested answers: where footage is kept,
                                   # a database on this computer, the dashboard, Claude Code's skills
For a machine that renders for others (a Mac mini):
  metarush service install --worker-only
After an upgrade: run `metarush migrate`, then `metarush service restart`
if you use the background service. Each version sets up its own renderer."""


def indent(text, n):
    return "\n".join(" " * n + line if line else line for line in text.split("\n"))


next_steps = indent(NEXT_STEPS, 6)

formula = f'''# typed: true
# frozen_string_literal: true

{header_comment}
#
# The cask (`brew install --cask {owner}/{tap_name}/metarush`) is the recommended install on macOS: this
# formula has no bottles, so Homebrew needs current Command Line Tools to install it there.
class Metarush < Formula
  desc "Skills-first, AI-native video editing harness: CLI, local dashboard and renderer"
  homepage "https://github.com/{repo}"
  version "{version}"
  license "MIT"

  METARUSH_TOKEN = ENV.fetch("HOMEBREW_GITHUB_API_TOKEN", "").freeze
  METARUSH_HEADERS = [
    "Accept: application/octet-stream",
    "X-GitHub-Api-Version: 2022-11-28",
    *("Authorization: Bearer #{{METARUSH_TOKEN}}" unless METARUSH_TOKEN.empty?),
  ].freeze

  depends_on "ffmpeg"
  depends_on "node"

  on_macos do
    on_arm do
{formula_block("darwin", "arm64")}    end
    on_intel do
{formula_block("darwin", "amd64")}    end
  end

  on_linux do
    on_arm do
{formula_block("linux", "arm64")}    end
    on_intel do
{formula_block("linux", "amd64")}    end
  end

  def install
    bin.install "metarush"
    pkgshare.install "renderer", "skills"
    doc.install Dir["docs/*"], "README.md", "CHANGELOG.md"
  end

  def caveats
    <<~EOS
{next_steps}
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/metarush version")
    system bin/"metarush", "renderer", "export", "--dir", testpath/"renderer"
    assert_path_exists testpath/"renderer/package-lock.json"
  end
end
'''

cask = f'''# typed: true
# frozen_string_literal: true

{header_comment}
cask "metarush" do
  token = ENV.fetch("HOMEBREW_GITHUB_API_TOKEN", "")
  headers = [
    "Accept: application/octet-stream",
    "X-GitHub-Api-Version: 2022-11-28",
    *("Authorization: Bearer #{{token}}" unless token.empty?),
  ]

  arch arm: "arm64", intel: "amd64"
  os macos: "darwin", linux: "linux"

  version "{version}"

  on_macos do
    on_arm do
{cask_block("darwin", "arm64")}    end
    on_intel do
{cask_block("darwin", "amd64")}    end
  end
  on_linux do
    on_arm do
{cask_block("linux", "arm64")}    end
    on_intel do
{cask_block("linux", "amd64")}    end
  end

  name "MetaRush"
  desc "Skills-first, AI-native video editing harness: CLI, local dashboard and renderer"
  homepage "https://github.com/{repo}"

  # What MetaRush runs to read footage and render (the formula depends on them too).
  depends_on formula: ["ffmpeg", "node"]

  binary "metarush_#{{version}}_#{{os}}_#{{arch}}/metarush"

  # Releases made without a Developer ID aren't notarized (D257): clear the quarantine flag Homebrew
  # sets on downloaded casks, so macOS runs the command without blocking it (harmless when notarized).
  postflight_steps do
    on_macos do
      run "/usr/bin/xattr", args: ["-dr", "com.apple.quarantine", "{{{{staged_path}}}}"], must_succeed: false
    end
  end

  caveats <<~EOS
{indent(NEXT_STEPS, 4)}
  EOS
end
'''

readme = f"""# Homebrew tap for MetaRush

MetaRush's cask and formula, written by `scripts/release.sh` in [{repo}](https://github.com/{repo}) for every
release:

```bash
brew tap {owner}/{tap_name}
brew install --cask {owner}/{tap_name}/metarush        # the binary (recommended), then: brew install ffmpeg node
#   or: brew install {owner}/{tap_name}/metarush       # the formula: also ffmpeg and node, but no bottles
#                                                       (on macOS it needs current Command Line Tools)
metarush init && metarush renderer install
```

The downloads go through GitHub's API, which limits anonymous requests; `HOMEBREW_GITHUB_API_TOKEN` (any GitHub
token) raises that limit.
"""

for rel, text in (("Formula/metarush.rb", formula), ("Casks/metarush.rb", cask), ("README.md", readme)):
    p = os.path.join(out_dir, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w") as f:
        f.write(text)
print(f"wrote the formula, the cask and the README for {version} to {out_dir}")
